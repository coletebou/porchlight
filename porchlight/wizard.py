DEV_PORTS = [(3000, "web"), (5173, "vite"), (8000, "api"), (8080, "http"), (4000, "app"), (5432, "postgres"),
             (6379, "redis"), (9000, "minio"), (11434, "ollama")]
CODE_DIRS = ("code", "src", "projects", "dev", "work", "git", "repos", "Developer")
SKIP_DIRS = {"node_modules", "vendor", "Library", "build", "dist", "target", ".venv", "venv", "__pycache__"}


def _subdirs(path: str, cap: int):
    """Up to cap child directories, from d_type (no stat per entry): a dir holding
    thousands of entries, or cloud-synced placeholders, must not stall init."""
    out = []
    try:
        with os.scandir(path) as it:
            for e in it:
                if len(out) >= cap:
                    break
                if not e.name.startswith(".") and e.name not in SKIP_DIRS and e.is_dir(follow_symlinks=False):
                    out.append(e.path)
    except OSError:
        pass
    return out


def find_repos(limit: int = 4, budget: float = 2.0) -> list:
    """The most recently used git checkouts one or two levels under the usual dirs,
    found within a time budget."""
    import time
    deadline = time.monotonic() + budget
    found = []
    for base in CODE_DIRS:
        root = os.path.join(core.HOME, base)
        if not os.path.isdir(root):
            continue
        for p in _subdirs(root, 400):
            if time.monotonic() > deadline:
                break
            if os.path.exists(os.path.join(p, ".git")):
                found.append(p)
                continue
            for q in _subdirs(p, 60):
                if os.path.exists(os.path.join(q, ".git")):
                    found.append(q)
    found.sort(key=lambda p: core.mtime(os.path.join(p, ".git", "index")), reverse=True)
    return found[:limit]


def _units() -> list:
    if not core.which("systemctl"):
        return []
    names = [u for u, _ in live.AUTO_UNITS if "*" not in u]
    st = live._systemctl_show(names)
    out = []
    for u, label in live.AUTO_UNITS:
        i = st.get(u) or st.get(u + ".service") or {}
        if i.get("LoadState") == "loaded" and i.get("ActiveState") == "active" and label not in [x[1] for x in out]:
            out.append((u, label))
    return out


def _launch_agents() -> list:
    d = os.path.join(core.HOME, "Library", "LaunchAgents")
    try:
        names = sorted(n[:-6] for n in os.listdir(d) if n.endswith(".plist"))
    except OSError:
        return []
    return [n for n in names if not n.startswith(("com.apple.", "com.google.keystone", "com.microsoft."))][:12]


def _ssh_aliases(limit=6) -> list:
    out = []
    for line in core.read_text(os.path.join(core.HOME, ".ssh", "config")).splitlines():
        parts = line.strip().split()
        if len(parts) >= 2 and parts[0].lower() == "host":
            out += [a for a in parts[1:] if not any(ch in a for ch in "*?!")]
    return out[:limit]


def _toml_list(items) -> str:
    return "[" + ", ".join('"%s"' % str(i).replace('"', '\\"') for i in items) + "]"


def generate() -> tuple:
    """(toml text, notes): a commented config tailored to this machine."""
    host = core.short_host()
    notes = []
    L = ["# porchlight configuration · generated by `porchlight init` on %s" % host,
         "# Reference: https://github.com/coletebou/porchlight/blob/master/docs/configuration.md",
         "# Everything is optional; delete what you do not need.", ""]
    # Top-level keys must come before the first [table] header, or TOML files them under it.
    repos = find_repos()
    if repos:
        L.append("repos = %s   # git checkouts shown in REPOS" % _toml_list(p.replace(core.HOME, "~", 1) for p in repos))
        notes.append("repos: %d recent checkouts" % len(repos))
    else:
        L.append('# repos = ["~/code/project"]')
    open_ports = [(p, label) for (p, label, ok) in live.ports([(p, label, "127.0.0.1") for p, label in DEV_PORTS]) if ok]
    if open_ports:
        L.append("ports = [%s]" % ", ".join('{ port = %d, label = "%s" }' % (p, label) for p, label in open_ports))
        notes.append("ports: %s listening now" % ", ".join(str(p) for p, _ in open_ports))
    else:
        L.append('# ports = [{ port = 5173, label = "vite" }]   # dev servers shown in NETWORK')
    L += ["",
          "[general]",
          '# label = "%s"            # display name (default: the hostname)' % host,
          '# identity = "personal"   # see [identities.*] to keep work and personal credentials apart',
          '# role = "auto"           # auto | dev | server',
          '# clock_secondary = "auto" # or "UTC", "Europe/Berlin", "" to hide']
    secrets = [p for p in ("~/.env_secrets", "~/.config/porchlight/secrets.env", "~/.secrets") if os.path.exists(core.expand(p))]
    if secrets:
        L.append("secrets_files = %s   # KEY=VALUE files the collector reads (never at render)" % _toml_list(secrets))
        notes.append("secrets: will read %s in the collector" % ", ".join(secrets))
    else:
        L.append('# secrets_files = ["~/.config/porchlight/secrets.env"]   # KEY=VALUE, chmod 600')
    L += ["", "[theme]", '# name = "porchlight"   # porchlight nord dracula gruvbox catppuccin tokyonight solarized daylight mono',
          '# accent = "ember"       # porchlight teal meadow dusk ember aurora orchid forest', ""]
    L += ["[banner]", '# text = "{label}"   # placeholders: {label} {host} {user} {identity}',
          '# font = "auto"       # auto | block | small | big | none | figlet:<font>',
          '# image = "~/logo.png" # rendered with chafa when it is installed', ""]

    units = _units()
    agents = _launch_agents() if core.IS_MAC else []
    L.append("[services]")
    if units:
        L.append("systemd = %s" % _toml_list(u for u, _ in units))
        notes.append("services: %s" % ", ".join(label for _, label in units))
    else:
        L.append('# systemd = ["nginx", "docker", { unit = "actions.runner.*", label = "runners" }]')
    if core.IS_MAC:
        L.append('launchd = ["homebrew.mxcl.*"%s]   # Homebrew services plus your LaunchAgents' % (
            "".join(', "%s"' % a for a in agents[:6])))
    L.append("")

    L += ["[sources.weather]", "# Without coordinates wttr.in locates you by IP. With them: Open-Meteo, then NWS (US).",
          "# latitude = 40.71", "# longitude = -74.01", '# units = "imperial"   # or "metric"', ""]
    for binary, source, setting in (("gcloud", "gcp_auth", 'project = "example-dev"'),
                                    ("az", "azure_auth", 'subscription = "Example development"')):
        if core.which(binary):
            L += ["# [sources.%s]  # opt in to a read-only cloud account check" % source,
                  "# " + setting, ""]
            notes.append("%s: found; enable sources.%s to check its account" % (binary, source))
    if core.which("aws"):
        L += ["# [sources.aws_account]   # the AWS panel: the account at list price, its budget, idle spend",
              '# profile = "readonly"     # the one profile it reads with; default: the first one STS accepts',
              '# home_regions = ["us-east-1"]',
              '# cost_explorer = "daily"  # adds Cost Explorer: one $0.01 request a day ("off" by default)', ""]
        notes.append("aws: found; the AWS panel reads the account (sources.aws_account)")
    drover_state = core.expand(os.environ.get("DROVER_STATE") or "~/.local/state/drover")
    if os.path.exists(os.path.join(drover_state, "daemon.json")):
        notes.append("drover: a daemon is running here; the DROVER panel shows its sessions")
    if core.which("tailscale") or os.path.exists("/Applications/Tailscale.app"):
        L += ["[sources.tailscale]", "required = false   # true: alert when tailscaled is not running", ""]
        notes.append("tailscale: found")
    L += ["# [sources.sites]   # public endpoints, probed from the hub",
          '# targets = [{ label = "blog", url = "https://example.com" }]', "",
          "# [sources.health]  # this machine's own health routes",
          '# targets = [{ label = "api", url = "http://127.0.0.1:3000/health", show = "version" }]', "",
          "# [sources.certs]",
          '# targets = ["example.com"]', "",
          "# [sources.files]   # size budgets for files that must stay small",
          '# targets = [{ path = "~/.claude/CLAUDE.md", max_bytes = 40000 }]', ""]
    if os.path.exists(os.path.join(core.HOME, ".claude")) or os.path.exists(os.path.join(core.HOME, ".codex", "auth.json")):
        notes.append("AI plan limits: Claude Code / Codex logins found (read-only usage queries)")
    have = sorted({src for var, src in SECRET_HINTS.items() if os.environ.get(var)})
    if core.which("gh"):
        rc, _, _ = core.run(["gh", "auth", "status"], 5)
        if rc == 0:
            have = sorted(set(have) | {"prs"})
    if have:
        notes.append("credentials found for: %s" % ", ".join(have))
    gh = []
    for p in repos:
        rc, url, _ = core.run(["git", "-C", p, "remote", "get-url", "origin"], 3)
        url = url.strip()
        if "github.com" in url:
            slug = url.split("github.com", 1)[1].lstrip(":/").rsplit(".git", 1)[0]
            if slug.count("/") == 1:
                gh.append(slug)
    L += ["[sources.github]   # CI on the default branch and open PRs, per repo",
          ("repos = %s" % _toml_list(gh[:3])) if gh else '# repos = ["owner/repo"]', '# branch = "main"', ""]
    peers = _ssh_aliases()
    L += ["[fleet]", "# List ssh aliases here to make this machine the hub: it pushes account-wide",
          "# data to every peer and pulls their status, all over your existing ssh config.",
          "# peers = %s" % _toml_list(peers[:3] or ["web1", "db1"]), "",
          '# [hosts."web-*"]     # per-machine overrides; globs match the hostname',
          '# general.role = "server"', ""]
    return "\n".join(L), notes


def run(host, flags, opts) -> int:
    text, notes = generate()
    if "--print" in flags:
        print(text)
        return 0
    path = core.CONFIG_PATH
    if os.path.exists(path) and "--force" not in flags:
        print("porchlight: %s exists (use --force to overwrite, or --print to see the suggestion)" % path)
        return 1
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as f:
        f.write(text + "\n")
    print("wrote %s" % path)
    for n in notes:
        print("  · " + n)
    print("next: porchlight collect   (fill the caches now)")
    print("      porchlight install all   (refresh every 5 min + show at login)")
    print("      porchlight doctor   (what runs here, and why not)")
    return 0
