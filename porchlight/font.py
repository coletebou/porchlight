FONTS = {"block": _BLOCK, "small": _SMALL, "big": _BLOCK}


def _bitmap(text: str, font: dict):
    """Rows of booleans for the whole string (glyphs joined by a one-pixel gap)."""
    glyphs = [font.get(ch.upper()) or font["?"] for ch in text]
    rows = len(glyphs[0].split("|")) if glyphs else 0
    out = [[] for _ in range(rows)]
    for gi, gl in enumerate(glyphs):
        parts = gl.split("|")
        for r in range(rows):
            if gi:
                out[r].append(False)
            out[r].extend(ch == "#" for ch in parts[r])
    return out


def render(text: str, font: str = "block", ascii: bool = False) -> list:
    """Banner lines for text in a built-in font (plain characters, no color).
    ascii: one '#' per pixel at full resolution, for terminals without Unicode."""
    if not text:
        return []
    bm = _bitmap(text, FONTS.get(font, _BLOCK))
    if ascii:
        return ["".join("#" if px else " " for px in row).rstrip() for row in bm]
    if font == "big":
        return ["".join("██" if px else "  " for px in row).rstrip() for row in bm]
    lines = []
    for r in range(0, len(bm), 2):
        top, bot = bm[r], (bm[r + 1] if r + 1 < len(bm) else [False] * len(bm[r]))
        lines.append("".join("█" if t and b else "▀" if t else "▄" if b else " " for t, b in zip(top, bot)).rstrip())
    return lines


def width_of(text: str, font: str) -> int:
    if not text:
        return 0
    bm = _bitmap(text, FONTS.get(font, _BLOCK))
    w = len(bm[0]) if bm else 0
    return w * 2 if font == "big" else w


def figlet(text: str, font: str, cache_dir: str) -> list:
    """figlet/toilet output, cached per (text, font): banners render on every login."""
    import hashlib
    key = hashlib.sha1(("%s\0%s" % (text, font)).encode()).hexdigest()[:16]
    path = os.path.join(cache_dir, "banner-%s.txt" % key)
    cached = core.read_text(path)
    if cached:
        return cached.splitlines()
    exe = core.which("figlet") or core.which("toilet")
    if not exe:
        return []
    argv = [exe, "-w", "400"] + (["-f", font] if font else []) + [text]
    rc, out, _ = core.run(argv, 3)
    if rc != 0 or not out.strip():
        return []
    try:
        os.makedirs(cache_dir, mode=0o700, exist_ok=True)
        with open(path, "w", encoding="utf-8") as f:
            f.write(out)
    except OSError:
        pass
    return out.splitlines()
